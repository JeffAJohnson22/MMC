        # Pick a random starting position making sure my range is the whole array
        start_index = random.randrange(0, len(arr))

        peakIndex, peakValleyValue = hillClimb(arr, start_index)
        
        # Check if we found the global maximum
        if peakValleyValue == targetValue:
            # Return the results if we found the global maximum
            return peakIndex, peakValleyValue, tries

