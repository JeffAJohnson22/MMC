# Hill climbing algorithm that finds a local maximum starting from a given index.
#B_A : hillClimb algorithm accepts an array and a starting index according to the prompt. 
def hillClimb(arr, start_index):
    if not arr:
        raise ValueError("Empty array")

    local_maximum_index = start_index

    while True:
        # if starting max index is greater than zero go left
        goLeft = local_maximum_index > 0
        # if starting max index is less than array length - 1 go right
        goRight = local_maximum_index < len(arr) - 1

        # if we are going left set left value to arr[local_maximum_index - 1] else -inf
        leftValue = arr[local_maximum_index - 1] if goLeft else float('-inf')

        # if we are going right set right value to arr[local_maximum_index + 1] else -inf
        # at first i thought this should be +inf but that would assume there's always a better value to the right
        # keep negative
        rightValue = arr[local_maximum_index + 1] if goRight else float('-inf')

        currValue = arr[local_maximum_index]

        # if goLeft and left value are greater than the current value slide over the index
        if goLeft and leftValue > currValue:
            local_maximum_index -= 1
            # If we slid over the index, we need to update the current value
            currValue = arr[local_maximum_index]

        # if goRight and right value are greater than the current value slide over the index
        elif goRight and rightValue > currValue:
            local_maximum_index += 1
            # If we slid over the index, we need to update the current value
            currValue = arr[local_maximum_index]

        # Handling the shoulders here - check both directions for possible peaks
        elif ((goLeft and leftValue == currValue) or 
              (goRight and rightValue == currValue)):
            
            foundBetter = False
            
            # Check left shoulder first
            # if the values are the same 
            if goLeft and leftValue == currValue:
                # Look ahead through the left shoulder
                tempIndex = local_maximum_index - 1
                while tempIndex >= 0 and arr[tempIndex] == currValue:
                    tempIndex -= 1
                # If there's a better number in the left shoulder, move left
                if tempIndex >= 0 and arr[tempIndex] > currValue:
                    local_maximum_index -= 1
                    foundBetter = True
            
            # Check right shoulder
            if not foundBetter and goRight and rightValue == currValue:
                # Look ahead through the right shoulder
                tempIndex = local_maximum_index + 1
                while tempIndex < len(arr) and arr[tempIndex] == currValue:
                    tempIndex += 1
                # If there's a better number in the right shoulder, move right
                if tempIndex < len(arr) and arr[tempIndex] > currValue:
                    local_maximum_index += 1
                    foundBetter = True
            
            # If no improvement found through shoulders, find leftmost position
            if not foundBetter:
                # Find the leftmost position
                shoulderStart = local_maximum_index
                while shoulderStart > 0 and arr[shoulderStart - 1] == currValue:
                    shoulderStart -= 1
                local_maximum_index = shoulderStart
                # B_B: hillClimb algorithm returns an index and a value of the local maximum according to the exact specifications of the prompt.
                return local_maximum_index, arr[local_maximum_index]
        else:
            # No neighbors or we have the best number
            # B_B: hillClimb algorithm returns an index and a value of the local maximum according to the exact specifications of the prompt. 
            return local_maximum_index, arr[local_maximum_index]

def lasVegasAlgo(arr):
    # Find the global maximum value in the array
    targetValue = max(arr)  
     # Counter for how many attempts we've made
    tries = 0 
    
    # Las Vegas has an unlimited runtime and doesn't stop until it has the answer
    while True:  
        # Increment attempt counter
        tries += 1  

        # Pick a random starting position making sure my range is the whole array
