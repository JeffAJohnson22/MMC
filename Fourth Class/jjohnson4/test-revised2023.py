# What are the limits of asymptotic analysis?

# Asymptotic analysis is limited by:
# It is limited by its inability to capture all aspects of an algorithm's performance. 
#  Like Real-world performance variations, Input characteristics, Memory usage

# Can Big O summarize how good an algorithm is?
# No. The worst case is Big O which may be too pessimistic

# Can Big O, Big Theta, and Big Omega summarize when an algorithm will be the best choice?
# No. The best choice depends on some factors like context, input, and everything else that needs to be considered for the output.


# Does amortized analysis settle the matter and point out the best algorithm for a specific problem?
# No. Amortized analysis does not guarantee finding the best algorithm for a specific problem. 
# It provides a way to analyze the average cost of an operation over a sequence of operations